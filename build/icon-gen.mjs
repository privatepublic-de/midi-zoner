// Writes build/icon.svg, the midi-zoner app icon, in the slate look of multisampler and A-112 Waves: a DIN-5 MIDI
// socket with a metal rim whose five pins glow in the five zone colours (one input, many zones).
// Run: node build/icon-gen.mjs, then npm run icon to render the PNGs and the .icns.
import fs from 'fs';
import path from 'path';

const dir = path.dirname(new URL(import.meta.url).pathname);
const ZONES = ['#4fc5fc', '#25d2c7', '#dab249', '#f99e65', '#ff968a']; // --zone-0 … --zone-4 in styles.css
const f = (n) => +n.toFixed(1);

const CX = 512, CY = 512;
const R = 330;            // socket rim
const INS = R * 0.76;     // dark insert
const PIN_R = 36;
const PIN_SPREAD = 0.62;  // pin circle, of the insert's radius

// DIN-5 female socket face: pins on a half circle over the centre (0°, ±45°, ±90° from the top), key notch at the bottom.
const pins = [-90, -45, 0, 45, 90].map((a) => {
  const t = (a - 90) * Math.PI / 180;
  return [CX + INS * PIN_SPREAD * Math.cos(t), CY + INS * PIN_SPREAD * Math.sin(t)];
});
const nw = R * 0.36, nh = R * 0.22;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- midi-zoner app icon (generated by build/icon-gen.mjs): a MIDI socket with a metal rim whose five pins glow in
       the five zone colours: one input, many zones. -->
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#2c323a"/><stop offset="1" stop-color="#14171b"/></linearGradient>
    <linearGradient id="ring" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#5a6370"/><stop offset="0.5" stop-color="#2c323a"/><stop offset="1" stop-color="#121519"/></linearGradient>
    <linearGradient id="ringEdge" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#e7eaee" stop-opacity="0.35"/><stop offset="1" stop-color="#e7eaee" stop-opacity="0.02"/></linearGradient>
    <linearGradient id="metal" x1="0" y1="0" x2="0.3" y2="1"><stop offset="0" stop-color="#7d8794"/><stop offset="0.45" stop-color="#454d58"/><stop offset="1" stop-color="#1c2026"/></linearGradient>
    <linearGradient id="bevelHi" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#e7eaee" stop-opacity="0.75"/><stop offset="0.5" stop-color="#e7eaee" stop-opacity="0.08"/><stop offset="1" stop-color="#000" stop-opacity="0.4"/></linearGradient>
    <linearGradient id="bevelLo" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#000" stop-opacity="0.75"/><stop offset="0.6" stop-color="#000" stop-opacity="0.2"/><stop offset="1" stop-color="#e7eaee" stop-opacity="0.3"/></linearGradient>
    <linearGradient id="insert" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#0b0d10"/><stop offset="1" stop-color="#1b1f25"/></linearGradient>
    <linearGradient id="gloss" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff" stop-opacity="0.28"/><stop offset="0.5" stop-color="#fff" stop-opacity="0"/></linearGradient>
    <filter id="shadow" x="-30%" y="-30%" width="160%" height="160%"><feDropShadow dx="0" dy="14" stdDeviation="14" flood-color="#000" flood-opacity="0.6"/></filter>
    <filter id="tileShadow" x="-10%" y="-10%" width="120%" height="125%"><feDropShadow dx="0" dy="12" stdDeviation="14" flood-color="#000" flood-opacity="0.5"/></filter>
    <filter id="glow" x="-100%" y="-100%" width="300%" height="300%"><feGaussianBlur stdDeviation="14"/></filter>
  </defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#tile)" filter="url(#tileShadow)"/>
  <rect x="101.5" y="101.5" width="821" height="821" rx="183.5" fill="none" stroke="#ffffff" stroke-opacity="0.07" stroke-width="3"/>
  <!-- rim: brushed metal, a bright bevel outside, a dark lip where the insert sinks in -->
  <g filter="url(#shadow)"><circle cx="${CX}" cy="${CY}" r="${R}" fill="url(#ring)"/></g>
  <circle cx="${CX}" cy="${CY}" r="${R - 2}" fill="none" stroke="url(#ringEdge)" stroke-width="4"/>
  <circle cx="${CX}" cy="${CY}" r="${R - 3}" fill="url(#metal)"/>
  <circle cx="${CX}" cy="${CY}" r="${R - 4}" fill="none" stroke="url(#bevelHi)" stroke-width="8"/>
  <circle cx="${CX}" cy="${CY}" r="${f(INS + 9)}" fill="none" stroke="url(#bevelLo)" stroke-width="18"/>
  <!-- insert and key notch -->
  <circle cx="${CX}" cy="${CY}" r="${f(INS)}" fill="url(#insert)"/>
  <circle cx="${CX}" cy="${CY}" r="${f(INS)}" fill="none" stroke="#000" stroke-opacity="0.6" stroke-width="6"/>
  <rect x="${f(CX - nw / 2)}" y="${f(CY + INS - nh)}" width="${f(nw)}" height="${f(nh + 8)}" rx="${f(nw * 0.22)}" fill="url(#ring)"/>
  <!-- pins in the zone colours -->
${pins.map(([x, y], i) => `  <circle cx="${f(x)}" cy="${f(y)}" r="${f(PIN_R * 1.5)}" fill="${ZONES[i]}" fill-opacity="0.35" filter="url(#glow)"/>
  <circle cx="${f(x)}" cy="${f(y)}" r="${PIN_R}" fill="${ZONES[i]}"/>
  <circle cx="${f(x)}" cy="${f(y)}" r="${PIN_R}" fill="url(#gloss)"/>`).join('\n')}
</svg>
`;

fs.writeFileSync(path.join(dir, 'icon.svg'), svg);
console.log('wrote build/icon.svg');
